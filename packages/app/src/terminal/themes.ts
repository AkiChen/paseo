export function terminalThemeLabel(id: TerminalThemeId): string {
  return TERMINAL_THEME_OPTIONS.find((option) => option.id === id)?.label ?? id;
}

export function resolveTerminalTheme(id: TerminalThemeId, appTheme: ITheme): ITheme {
  return id === "app" ? appTheme : TERMINAL_THEMES[id];
}
