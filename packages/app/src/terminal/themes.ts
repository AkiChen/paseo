export type TerminalThemeId = (typeof TERMINAL_THEME_OPTIONS)[number]["id"];

export const DEFAULT_TERMINAL_THEME = "app" satisfies TerminalThemeId;

export function isTerminalThemeId(value: string): value is TerminalThemeId {
  return TERMINAL_THEME_OPTIONS.some((option) => option.id === value);
}

interface TerminalPalette {
  background: string;
  foreground: string;
  cursor?: string;
  selectionBackground: string;
  ansi: readonly [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ];
}

function createTheme(palette: TerminalPalette): ITheme {
  const [
    black,
    red,
    green,
    yellow,
    blue,
    magenta,
    cyan,
    white,
    brightBlack,
    brightRed,
    brightGreen,
    brightYellow,
    brightBlue,
    brightMagenta,
    brightCyan,
    brightWhite,
  ] = palette.ansi;
  const cursor = palette.cursor ?? palette.foreground;

  return {
    background: palette.background,
    foreground: palette.foreground,
    cursor,
    cursorAccent: palette.background,
    selectionBackground: palette.selectionBackground,
    black,
    red,
    green,
    yellow,
    blue,
    magenta,
    cyan,
    white,
    brightBlack,
    brightRed,
    brightGreen,
    brightYellow,
    brightBlue,
    brightMagenta,
    brightCyan,
    brightWhite,
  };
}

